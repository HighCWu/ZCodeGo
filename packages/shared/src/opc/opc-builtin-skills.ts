/**
 * zcode-go OPC 内置技能包（16 技能）。
 *
 * 格式与 alirezarezvani/claude-skills 的 SKILL.md 同构（frontmatter：
 * name/description + metadata.category；description 写清触发时机与相邻技能消歧，
 * 这是技能被正确选用的关键）。正文遵循「工作流 + 边界 + 反模式」结构。
 * 初始版本落盘到 <workspace>/.opc/skills/<id>/SKILL.md，后续经「技能升级」流自主迭代。
 */
export interface OpcBuiltinSkill {
  name: string;
  markdown: string;
}

function skill(
  name: string,
  description: string,
  category: string,
  sections: Array<{ heading: string; items: string[] }>,
): OpcBuiltinSkill {
  const body = [
    "---",
    `name: ${name}`,
    `description: ${description}`,
    "metadata:",
    "  version: 1.0.0",
    `  category: ${category}`,
    "---",
    "",
    ...sections.flatMap((section) => [
      `## ${section.heading}`,
      "",
      ...section.items,
      "",
    ]),
  ];
  return { name, markdown: body.join("\n") };
}

