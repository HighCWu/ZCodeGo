/**
 * zcode-go OPC 内置角色模板包（24 角色）。
 *
 * 格式与 HKUDS/OpenOPC 的 talent 模板同构（五字段 frontmatter：
 * name/description/color/emoji/vibe + 章节化正文），可直接被 parseOpcRoleTemplate
 * 解析；分类覆盖 OpenOPC 九大垂直领域（研发/研究/金融/销售/营销/内容/行业助手/
 * 财税/教育）。招聘时由 UI 解出五字段传给 reducer。
 */
export interface OpcBuiltinRoleTemplate {
  name: string;
  markdown: string;
}

function roleTemplate(
  name: string,
  description: string,
  color: string,
  emoji: string,
  vibe: string,
  persona: string,
  mission: string,
  rules: string[],
  workflow: string[],
  deliverables: string[],
): OpcBuiltinRoleTemplate {
  const markdown = [
    "---",
    `name: ${name}`,
    `description: ${description}`,
    `color: ${color}`,
    `emoji: ${emoji}`,
    `vibe: ${vibe}`,
    "---",
    "",
    "## 人设与使命",
    "",
    persona,
    "",
    `核心使命：${mission}`,
    "",
    "## 核心规则",
    "",
    ...rules.map((rule) => `- ${rule}`),
    "",
    "## 工作流",
    "",
    ...workflow.map((step, index) => `${index + 1}. ${step}`),
    "",
    "## 交付物",
    "",
    ...deliverables.map((item) => `- ${item}`),
    "",
    "## 沟通与经验沉淀",
    "",
    "- 结论先行：先给结果与建议，再给依据；不确定时明确标注置信度。",
    "- 任务结束后自查：哪些做法值得固化为经验（供复盘蒸馏进个人档案与共享 playbook）。",
    "",
  ].join("\n");
  return { name, markdown };
}

